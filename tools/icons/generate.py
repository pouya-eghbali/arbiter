#!/usr/bin/env python3
"""Generate the QML SVG registry from the pinned, vendored Lucide subset. No network."""
import json
from pathlib import Path
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parents[2]
assets = root / 'assets/icons/lucide'
icons = {}
for path in sorted(assets.glob('*.svg')):
    svg = path.read_text().strip()
    element = ET.fromstring(svg)
    assert element.attrib['viewBox'] == '0 0 24 24', path
    assert element.attrib['stroke'] == 'currentColor', path
    icons[path.stem] = svg
revision = (assets / 'REVISION').read_text().strip()
(root / 'qml/ui/LucideIcons.js').write_text(
    '.pragma library\n// Generated by tools/icons/generate.py; do not edit.\n'
    '// Lucide ' + revision + '; ISC / Feather MIT. See licenses/Lucide.txt.\n'
    'var icons = ' + json.dumps(icons, indent=4, ensure_ascii=False) + ';\n')
print(f'Generated {len(icons)} Lucide icons')
